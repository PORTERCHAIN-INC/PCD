"""Models and migrations must describe the same schema (``alembic check`` equivalent).

Runs against the throwaway test database that ``scripts/test-infra.sh up`` migrated to head.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext

from porterchain_api.db import Base, engine

_ENV = Path(__file__).resolve().parents[1] / "alembic" / "env.py"


def _env_filters():
    src = _ENV.read_text()
    ns: dict = {}
    import sqlalchemy

    ns["text"] = sqlalchemy.text
    exec(src[src.index("_EXTENSION_TABLES: set") : src.index("settings = get_settings()")], ns)
    return ns


def test_models_match_migrated_database() -> None:
    # Same model imports as alembic/env.py (ends with schema_extras).
    src = _ENV.read_text()
    exec(src[src.index("# Import all models") : src.index("config = context.config")], {})

    ns = _env_filters()
    with engine.connect() as conn:
        try:
            ns["_EXTENSION_TABLES"].update(ns["load_extension_tables"](conn))
        except Exception as exc:  # pragma: no cover - DB missing
            pytest.skip(f"test database unavailable: {exc}")
        if not conn.exec_driver_sql("SELECT to_regclass('alembic_version')").scalar():
            pytest.skip("test database not migrated")
        ctx = MigrationContext.configure(conn, opts={"include_object": ns["include_object"]})
        diff = compare_metadata(ctx, Base.metadata)
    assert diff == [], f"model/migration drift: {diff[:10]}"


def test_extension_tables_are_never_autogenerated_as_drops() -> None:
    ns = _env_filters()
    ns["_EXTENSION_TABLES"].update({"addrfeat"})

    class _T:
        schema = None

    assert ns["include_object"](_T(), "addrfeat", "table", True, None) is False
    assert ns["include_object"](_T(), "orders", "table", True, None) is True
